var currentLang = localStorage.getItem('appLang') || 'en';

function changeLanguage(val) {
    currentLang = val;
    window.currentLang = val;
    localStorage.setItem('appLang', val);
    applyTranslations();
    if (typeof updateSettingsLive === 'function') updateSettingsLive();
}

function applyTranslations() {
    const dict = translations[currentLang] || translations['ru'] || translations['en'];
    if (!dict) return;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) el.innerHTML = dict[key];
    });

    const statusText = document.getElementById('statusText');
    if (statusText) {
        if (statusText.innerText.toUpperCase().includes('CONNECT') ||
            statusText.innerText.toUpperCase().includes('ПОДКЛЮЧ') ||
            statusText.innerText.toUpperCase().includes('З\'ЄДН')) {
            statusText.innerText = dict['connected'];
        } else {
            statusText.innerText = dict['disconnected'];
        }
    }

    const micLabel = document.getElementById('micMuteLabel');
    if (micLabel) micLabel.innerText = window.isMicMuted ? dict.micMuted : dict.micOn;

    if (!window.selectedDevice) {
        const sdt = document.getElementById('selectedDeviceText');
        if (sdt) sdt.innerText = dict.waitingDevice;
    }
}

window.translations = translations;
window.currentLang = currentLang;
window.changeLanguage = changeLanguage;
window.applyTranslations = applyTranslations;
